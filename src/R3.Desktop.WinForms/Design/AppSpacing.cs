namespace R3.Desktop.WinForms.Design;

/// <summary>Spacing scale in 96-DPI logical pixels (WinForms scales them per monitor). No other margin/padding values.
/// View padding = LG, between stacked regions = SM, label→control = XS, between control groups = MD.</summary>
public static class AppSpacing
{
    public const int XS = 4;
    public const int SM = 8;
    public const int MD = 12;
    public const int LG = 16;
    public const int XL = 24;
    public const int XXL = 32;
}
